  /**
   * Helper: Normalize string (remove zero-width chars, collapse spaces)
   */
  function clean(str) {
    if (!str) return '';
    return str.replace(/[\u200B-\u200D\uFEFF]/g, '')
              .replace(/\s+/g, ' ')
              .trim();
  }

  /**
   * Emoji & symbol regex for stripping/re-attaching prefixes
   */
  const SYMBOL_PREFIX_REGEX = /^([\uD800-\uDBFF][\uDC00-\uDFFF]|[\u2600-\u27BF]|[\u2300-\u23FF]|\u200D|[\uFE00-\uFE0F]|[\u2B50-\u2B55]|[\u3030-\u303D]|[✓•🗓📍💡📅🗺📄🧪🥗📊💬📥📤🧘‍♀️▶↺🌸👥🔴✍️🚨🏥👩‍⚕️🚑📞🍼🔔👤💾📷🗑️🚪📝🔒🛡️⚡😴🤢]+|\s+)+/u;

  /**
   * Build complete bidirectional translation lookup Map for target language
   */
  let cachedLookup = null;
  let cachedTargetLang = null;

  function getLookupMap(targetLang) {
    if (cachedLookup && cachedTargetLang === targetLang) {
      return cachedLookup;
    }

    const map = new Map();
    const targetDict = DICTIONARY[targetLang] || {};

    // Collect all base English keys from all language dicts
    const allBaseKeys = new Set();
    Object.keys(DICTIONARY).forEach(lang => {
      Object.keys(DICTIONARY[lang]).forEach(k => allBaseKeys.add(k));
    });

    allBaseKeys.forEach(enKey => {
      const cleanEn = clean(enKey);
      if (!cleanEn) return;
      const lowerEn = cleanEn.toLowerCase();

      let targetVal = targetDict[enKey];
      if (targetVal === undefined) {
        targetVal = enKey;
      }

      // Map English key to target
      map.set(cleanEn, targetVal);
      map.set(lowerEn, targetVal);

      // Also map every other language representation of this key back to target
      Object.keys(DICTIONARY).forEach(langCode => {
        const langVal = DICTIONARY[langCode][enKey];
        if (langVal) {
          const cleanLang = clean(langVal);
          if (cleanLang) {
            map.set(cleanLang, targetVal);
            map.set(cleanLang.toLowerCase(), targetVal);
          }
        }
      });
    });

    cachedLookup = map;
    cachedTargetLang = targetLang;
    return map;
  }

  /**
   * Universal Deep DOM Text Node & Attribute Translator
   */
  let isTranslating = false;

  function translateEntireDOM(targetLang) {
    if (!targetLang) targetLang = 'en';
    if (isTranslating) return;
    isTranslating = true;

    try {
      const lookup = getLookupMap(targetLang);

      // Collect all relevant DOM containers
      const roots = document.querySelectorAll(
        '.site-main, .dashboard-site-layout, .dash-tab-pane, .module-card, .appointment-highlight-card, .webinar-highlight-card, .dash-modal-overlay, .dashboard-sidebar, .onboarding-section'
      );

      const skipTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'IFRAME']);
      const skipIds = new Set([
        'sidebarAvatar', 'profileMainAvatarDisplay', 'dashHeroCountdown',
        'kickCountWebsiteLabel', 'waterCountWebsiteLabel', 'profCurrentPwd',
        'profNewPwd', 'profConfirmPwd'
      ]);

      roots.forEach(root => {
        const elements = root.querySelectorAll('*');
        elements.forEach(el => {
          if (skipTags.has(el.tagName)) return;
          if (skipIds.has(el.id)) return;
          if (el.classList.contains('user-name')) return;

          // Translate placeholders
          if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            const ph = el.getAttribute('placeholder');
            if (ph) {
              const cleanPh = clean(ph);
              const hit = lookup.get(cleanPh) || lookup.get(cleanPh.toLowerCase());
              if (hit) {
                el.setAttribute('placeholder', hit);
              }
            }
            return;
          }

          // Translate text child nodes
          el.childNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE) {
              const raw = node.nodeValue;
              if (!raw || !raw.trim()) return;

              const cleanText = clean(raw);
              if (!cleanText) return;

              // 1. Direct match
              let hit = lookup.get(cleanText) || lookup.get(cleanText.toLowerCase());

              // 2. Prefix symbol stripping match (e.g. "🩺 Clinical Care" -> "Clinical Care")
              let leadingSymbol = '';
              if (!hit) {
                const match = raw.match(SYMBOL_PREFIX_REGEX);
                if (match && match[0]) {
                  leadingSymbol = match[0];
                  const strippedText = clean(raw.slice(match[0].length));
                  hit = lookup.get(strippedText) || lookup.get(strippedText.toLowerCase());
                }
              }

              if (hit) {
                const leadWhitespace = raw.match(/^\s*/)[0];
                const trailWhitespace = raw.match(/\s*$/)[0];
                if (leadingSymbol) {
                  node.nodeValue = leadWhitespace + leadingSymbol + hit + trailWhitespace;
                } else {
                  node.nodeValue = leadWhitespace + hit + trailWhitespace;
                }
              }
            }
          });
        });
      });
    } finally {
      isTranslating = false;
    }
  }

  window.BellyBandTranslateAll = translateEntireDOM;

